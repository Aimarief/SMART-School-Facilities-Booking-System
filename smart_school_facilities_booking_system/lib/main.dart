  bool _notifAll = true;
  bool _notifApprovalBook = true;
  bool _notifNewBook = true;
  bool _notifReminder = true;
  bool _notifUpdatedBook = true;

  Timer? _minuteTicker;
  AppLifecycleState _lifeState = AppLifecycleState.resumed;
  // --- Build a local DateTime from "YYYY-MM-DD" + either slotKey "HHmm" or start "HH:MM"
  DateTime? _toLocalDateTime(String dateYMD, {String? slotKey, String? startHHmm}) {
    try {
      final p = dateYMD.split('-');                 // split date parts
      if (p.length != 3) return null;
      final int y = int.parse(p[0]);
      final int m = int.parse(p[1]);
      final int d = int.parse(p[2]);

      String t = '';
      if (startHHmm != null && startHHmm.trim().isNotEmpty) {
        t = startHHmm.trim();                       // use "HH:MM" if given
      } else if (slotKey != null && slotKey.trim().isNotEmpty) {
        String k = slotKey.trim().replaceAll(':', '');  // use "HHmm"
        if (k.length < 4) k = k.padLeft(4, '0');
        t = k.substring(0, 2) + ':' + k.substring(2, 4); // -> "HH:MM"
      } else {
        return null;
      }

      final tp = t.split(':');                      // parse time
      if (tp.length != 2) return null;
      final int hh = int.parse(tp[0]);
      final int mm = int.parse(tp[1]);

      return DateTime(y, m, d, hh, mm);            // local device time
    } catch (_) {
      return null;                                  // invalid -> null
    }
  }
  int _pickOneThreshold(Duration leftAtApproval) {
    final h = leftAtApproval.inHours;
    if (h >= 24) return 24;
    if (h >= 12) return 12;
    if (h >= 6)  return 6;
    if (h >= 1)  return 1;
    return 0; // too close -> no reminder
  }



  Future<void> _resyncUpcomingReminders(String uid) async {
    if (kIsWeb) return;

    const freshWindow = Duration(minutes: 5); // how long the trigger stays valid

    final qs = await FirebaseFirestore.instance
        .collection('Bookings')
        .where('userId', isEqualTo: uid)
        .where('approval', whereIn: ['accepted', 'approved'])
        .where('status', isEqualTo: 'upcoming')
        .get();

    for (final doc in qs.docs) {
      final m = doc.data();

      // Skip cancelled/deleted
      if ((m['deleted'] == true) ||
          ((m['status'] ?? '').toString().toLowerCase() == 'cancelled')) {
        await doc.reference.set({'reminderSent': {'any': true}}, SetOptions(merge: true));
        continue;
      }

      // Build start time from your fields
      final String date    = (m['bookingDate'] ?? '').toString().trim();
      final String slotKey = (m['slotKey'] ?? '').toString().trim();
      final String startStr= (m['start'] ?? '').toString().trim();
      final DateTime? startAt = _toLocalDateTime(
        date,
        slotKey: slotKey.isNotEmpty ? slotKey : null,
        startHHmm: startStr.isNotEmpty ? startStr : null,
      );
      if (startAt == null) continue;

      // Baseline time (when it was approved/created)
      DateTime? approvedAt;
      final a = m['approvedAt'];
      if (a is Timestamp) approvedAt = a.toDate();
      approvedAt ??= (m['createdAt'] is Timestamp)
          ? (m['createdAt'] as Timestamp).toDate()
          : null;
      if (approvedAt == null) continue;

      // --- RE-ARM + PLAN + FIRE ---

      // Read previous plan/flag
      Map<String, dynamic> sent =
          (m['reminderSent'] as Map?)?.cast<String, dynamic>() ?? {};
      final Map<String, dynamic> oldPlan =
          (sent['plan'] as Map?)?.cast<String, dynamic>() ?? {};

      DateTime? plannedStartAt;
      final plannedStartRaw = oldPlan['startAt'];
      if (plannedStartRaw is Timestamp) plannedStartAt = plannedStartRaw.toDate();

      // If reminder was done BUT start time changed -> clear to re-arm
      final bool timeChanged =
          plannedStartAt == null || (plannedStartAt.difference(startAt).inMinutes).abs() >= 1;
      if ((sent['any'] as bool? ?? false) && timeChanged) {
        await doc.reference.set({'reminderSent': {}}, SetOptions(merge: true));
        sent = {}; // re-armed
      }

      // If still marked done and time didn't change, skip
      if ((sent['any'] as bool?) == true) continue;

      // Choose threshold after possible re-arm
      final now = DateTime.now();
      final Duration basis = sent.isEmpty
          ? startAt.difference(now)                 // re-armed or first plan
          : startAt.difference(approvedAt);         // existing plan baseline

      final int chosenH = _pickOneThreshold(basis);
      if (chosenH == 0) {
        // too close -> no reminder
        final out0 = Map<String, dynamic>.from(sent);
        out0['any'] = true;
        await doc.reference.set({'reminderSent': out0}, SetOptions(merge: true));
        continue;
      }

      final DateTime trigger = startAt.subtract(Duration(hours: chosenH));

      // Save plan and decide: missed / wait / fire
      final Map<String, dynamic> out = Map<String, dynamic>.from(sent);
      out['plan'] = {
        'h': chosenH,
        'triggerAt': Timestamp.fromDate(trigger),
        'startAt': Timestamp.fromDate(startAt),
      };

      if (now.isAfter(trigger.add(freshWindow))) {
        // Missed -> mark done, no late reminder
        out['any'] = true;
        await doc.reference.set({'reminderSent': out}, SetOptions(merge: true));
        continue;
      }

      if (now.isBefore(trigger)) {
        // Not yet time -> store plan only
        await doc.reference.set({'reminderSent': out}, SetOptions(merge: true));
        continue;
      }

      // Within window -> show once and mark done
      if (_notifAll && _notifReminder) {
        final fac = (m['facilityName'] ?? m['facility'] ?? 'Booking').toString();
        LocalNotify.show(
          id: (doc.id + '_rem').hashCode & 0x7fffffff,
          title: 'Booking reminder',
          body: '$fac • ${chosenH}h before start',
        );
      }
      out['any'] = true;
      await doc.reference.set({'reminderSent': out}, SetOptions(merge: true));
    }
  }




  // -----------------------------------------
  // read or create "inboxLastSeen" on user doc
  // -----------------------------------------
  Future<Timestamp> _readOrInitLastSeenFS(String uid) async {
    final docRef = FirebaseFirestore.instance
        .collection('UserInformation')
        .doc(uid);                                       // point to user doc

    final snap = await docRef.get();                     // read once

    if (snap.exists == true) {                           // if doc exists
      final data = snap.data();                          // get map
      if (data != null &&
          data.containsKey('inboxLastSeen') &&
          data['inboxLastSeen'] is Timestamp) {
        return data['inboxLastSeen'] as Timestamp;       // return stored ts
      }
    }

    final now = Timestamp.now();                         // first time -> now
    await docRef.set({'inboxLastSeen': now}, SetOptions(merge: true));
    return now;                                          // return the saved ts
  }

  // -----------------------------------------
  // write newest lastSeen after processing
  // -----------------------------------------
  Future<void> _writeLastSeenFS(String uid, Timestamp ts) async {
    final docRef = FirebaseFirestore.instance
        .collection('UserInformation')
        .doc(uid);                                       // point to user doc
    await docRef.set({'inboxLastSeen': ts}, SetOptions(merge: true));
  }

  // -------------------------------------------------------
  // Start inbox listener (only docs newer than lastSeen)
  // -------------------------------------------------------
  Future<void> _startInboxListenerFS(User user) async {
    _inboxSub?.cancel();                                 // avoid duplicate subs

    final Timestamp lastSeenAtStart =
    await _readOrInitLastSeenFS(user.uid);           // get baseline ts

    final Query<Map<String, dynamic>> q = FirebaseFirestore.instance
        .collection('UserInformation')
        .doc(user.uid)
        .collection('Inbox')
        .where('createdAt', isGreaterThan: lastSeenAtStart)
        .orderBy('createdAt');                           // sort by time

    _inboxSub = q.snapshots().listen((qs) async {
      Timestamp newest = lastSeenAtStart;                // track newest ts

      for (final c in qs.docChanges) {
        if (c.type != DocumentChangeType.added) {        // only new docs
          continue;
        }

        final m = c.doc.data();                          // get map
        if (m == null) { continue; }

        if (m['isRead'] == true) {                       // already read -> skip popup
          continue;
        }

        if (_notifAll == false) {                        // master off -> skip all
          continue;
        }

        // safe read createdAt
        Timestamp createdAt = Timestamp.now();           // fallback now
        final any = m['createdAt'];
        if (any is Timestamp) {
          createdAt = any;
        }

        // simple fields
        final String type = (m['type'] ?? '').toString();
        final String facility =
        (m['facilityName'] ?? m['facility'] ?? 'SMART booking').toString();
        final String approval =
        (m['approval'] ?? m['approvalStatus'] ?? '').toString().toLowerCase();

        // build title/body with basic if/else only
        String title;
        String body = facility;

        if (type == 'booking_created') {
          if (_notifNewBook == false) { continue; }
          if (approval == 'pending') { continue; }
          title = 'Booked successfully';
        } else if (type == 'booking_updated') {
          if (_notifUpdatedBook == false) { continue; }
          title = 'Booking updated';
        } else if (type == 'approval_status') {
          if (_notifApprovalBook == false) { continue; }
          if (approval.contains('accept') || approval.contains('approv')) {
            title = 'Facility approved';
          } else if (approval.contains('reject') ||
              approval.contains('declin') ||
              approval.contains('deni')) {
            title = 'Facility rejected';
          } else {
            title = 'Booking updated';
          }
        } else if (type == 'reminder') {
          // FYI: real reminders now come via FCM.
          // We still allow Inbox "reminder" entries for history if you create them,
          // but you can skip showing a popup here if you want.
          if (_notifReminder == false) { continue; }
          title = 'Booking reminder';
        } else if (type == 'request_update') {
          title = 'Action needed';
          final String date = (m['bookingDate'] ?? '').toString().trim();
          final String facName = (m['facilityName'] ?? '').toString().trim();
          if (facName.isNotEmpty && date.isNotEmpty) {
            body = '$facName • $date — please change booking date';
          } else if (date.isNotEmpty) {
            body = 'Please change your booking date: $date';
          } else {
            body = 'Please change your booking date';
          }
        } else if (type == 'booking_deleted') {
          if (_notifReminder == false) { continue; }
          title = 'Your booking have been deleted';
        } else {
          title = 'Notification';
          final String msg = (m['message'] ?? '').toString().trim();
          if (msg.isNotEmpty) { body = msg; }
        }

        // show a local heads-up (mobile only)
        if (!kIsWeb) {
          LocalNotify.show(
            id: c.doc.id.hashCode & 0x7fffffff,          // stable int id
            title: title,
            body: body,
          );
        }

        // remember newest time we saw
        if (createdAt.compareTo(newest) > 0) {
          newest = createdAt;
        }
      }

      // bump lastSeen after processing
      if (newest.compareTo(lastSeenAtStart) > 0) {
        await _writeLastSeenFS(user.uid, newest);
      }
    });
  }

