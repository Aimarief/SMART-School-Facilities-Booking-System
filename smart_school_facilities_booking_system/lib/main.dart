// -------------------------------------------------------
// Initialize local notification channels (Android)
// We keep 2 channels:
//  - inbox_updates: your normal inbox events (approval, created, etc.)
//  - booking_reminders: used by FCM reminder popups (foreground) + default for background
// -------------------------------------------------------
Future<void> initLocalNotifications() async {
  // step 1: Android specific init (uses your mipmap launcher icon)
  const AndroidInitializationSettings androidInit =
  AndroidInitializationSettings('@mipmap/ic_launcher');

  // step 2: generic init settings (Android only for now)
  const InitializationSettings initSettings =
  InitializationSettings(android: androidInit);

  // step 3: initialize the plugin
  await localNotifications.initialize(initSettings);

  // step 4: create "inbox_updates" channel (high importance)
  const AndroidNotificationChannel inboxChannel = AndroidNotificationChannel(
    'inbox_updates',                                     // channel id
    'Inbox Updates',                                     // channel name
    description: 'Booking & approval alerts',            // channel description
    importance: Importance.max,                          // heads-up on Android 12+
  );

  // step 5: create "booking_reminders" channel (high importance)
  const AndroidNotificationChannel remindersChannel = AndroidNotificationChannel(
    'booking_reminders',                                 // MUST match Manifest meta-data
    'Booking Reminders',                                 // channel name
    description: 'Time-based reminders from FCM',        // channel description
    importance: Importance.high,                         // high is enough here
  );

  // step 6: resolve Android implementation to create channels
  final androidImpl = localNotifications
      .resolvePlatformSpecificImplementation<
      AndroidFlutterLocalNotificationsPlugin>();

  // step 7: actually create both channels
  await androidImpl?.createNotificationChannel(inboxChannel);
  await androidImpl?.createNotificationChannel(remindersChannel);

  // step 8: Android 13+ runtime permission (no-op on older)
  await androidImpl?.requestNotificationsPermission();
}

