// -------------------------------------------------------
// A small wrapper to let GoRouter refresh on auth changes
// -------------------------------------------------------
class GoRouterRefreshStream extends ChangeNotifier {
  // constructor: listen to any stream and call notify when it emits
  GoRouterRefreshStream(Stream<dynamic> stream) {
    notifyListeners();                                    // tell listeners once now
    _subscription = stream
        .asBroadcastStream()
        .listen((_) => notifyListeners());                // notify when stream emits
  }

  late final StreamSubscription<dynamic> _subscription;   // remember sub to cancel

  @override
  void dispose() {
    _subscription.cancel();                               // stop listening
    super.dispose();
  }
}

